CREATE TABLE ta (
    idta int IDENTITY(1,1) PRIMARY KEY,
    statust integer DEFAULT 0,
    status integer DEFAULT 0,
    parent integer DEFAULT 0,
    child integer DEFAULT 0,
    script integer DEFAULT 0,
    idroute nvarchar(35) DEFAULT '',
    filename nvarchar(256) DEFAULT '',
    frompartner nvarchar(35) DEFAULT '',
    topartner nvarchar(35) DEFAULT '',
    fromchannel nvarchar(35) DEFAULT '',
    tochannel nvarchar(35) DEFAULT '',
    editype nvarchar(35) DEFAULT '',
    messagetype nvarchar(35) DEFAULT '',
    alt nvarchar(35) DEFAULT '',
    divtext nvarchar(128) DEFAULT '',
    [merge] bit DEFAULT 0,
    nrmessages integer DEFAULT 1,
    testindicator nvarchar(10) DEFAULT '',
    reference nvarchar(256) DEFAULT '',
    frommail nvarchar(256) DEFAULT '',
    tomail nvarchar(256) DEFAULT '',
    charset nvarchar(35) DEFAULT '',
    retransmit bit DEFAULT 0,
    contenttype nvarchar(35) DEFAULT 'text/plain',
    errortext nvarchar(max),
    ts datetime2 DEFAULT CURRENT_TIMESTAMP,
    confirmasked bit DEFAULT 0,
    confirmed bit DEFAULT 0,
    confirmtype nvarchar(35) DEFAULT '',
    confirmidta integer DEFAULT 0,
    envelope nvarchar(35) DEFAULT '',
    botskey nvarchar(64) DEFAULT '',
    cc nvarchar(512) DEFAULT '',
    rsrv1 nvarchar(128) DEFAULT '',
    rsrv2 integer DEFAULT 0,
    rsrv3 nvarchar(35) DEFAULT '',
    rsrv4 integer DEFAULT 0,
    filesize integer DEFAULT 0,
    numberofresends integer DEFAULT 0,
    rsrv5 nvarchar(256) DEFAULT ''
);
CREATE INDEX ta_parent ON ta (parent);
CREATE INDEX ta_reference ON ta (reference);
